// Regenerates extension/src/icon-data.js from the 64px icon.
// The content script uses it as a data: URL for the favicon and the nav logo,
// because Safari won't reliably let the page load images from the extension.
// Run: node scripts/embed-icon.js
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const png = fs.readFileSync(path.join(root, 'extension/images/icon-64.png'));
const out = `// Generated by scripts/embed-icon.js. Do not edit.
globalThis.PERCH_ICON = 'data:image/png;base64,${png.toString('base64')}';
`;
fs.writeFileSync(path.join(root, 'extension/src/icon-data.js'), out);
console.log(`wrote extension/src/icon-data.js (${out.length} bytes)`);
